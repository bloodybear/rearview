import Foundation
import ApplicationServices

// All offsets are UTF-16. Never split surrogate pairs or accept stalled/out-of-bounds ranges.
package enum TextRangeSafety {
    static func advances(_ range: CFRange, from offset: Int, in text: String) -> Bool {
        valid(range, in: text) && range.location == offset && range.location + range.length > offset
    }
    static func retreats(_ range: CFRange, before offset: Int, in text: String) -> Bool {
        valid(range, in: text) && range.location < offset && range.location + range.length == offset
    }
    // A native visual line may start in the preceding emoji/formatted node.
    // Restrict only when that line contains the exact remaining source prefix.
    // We then re-query AX with this node's original start; never clip a rectangle.
    static func lineCrossesNodeStart(_ line: String, before offset: Int, in text: String) -> Bool {
        guard valid(CFRange(location: 0, length: offset), in: text) else { return false }
        let units = Array(line.utf16)
        return units.count > offset && units.suffix(offset).elementsEqual(text.utf16.prefix(offset))
    }
    static func visibility(_ box: CGRect, in clip: CGRect) -> String {
        guard !box.isNull, !box.isInfinite, box.width > 0, box.height > 0 else { return "invalid_bounds" }
        if !clip.intersects(box) { return "outside" }
        return clip.contains(box) ? "inside_unverified" : "partial_unknown"
    }

    static func valid(_ range: CFRange, in text: String) -> Bool {
        let units = Array(text.utf16)
        guard range.location >= 0, range.length > 0, range.location <= units.count,
              range.length <= units.count - range.location else { return false }
        func boundary(_ i: Int) -> Bool {
            !(i > 0 && i < units.count && (0xD800...0xDBFF).contains(units[i-1]) && (0xDC00...0xDFFF).contains(units[i]))
        }
        return boundary(range.location) && boundary(range.location + range.length)
    }
    static func uniqueOffset(_ child: String, in parent: String) -> Int? {
        guard !child.isEmpty else { return nil }
        let source = parent as NSString
        let first = source.range(of: child)
        guard first.location != NSNotFound else { return nil }
        let next = first.location + 1
        if next < source.length && source.range(of: child, range: NSRange(location: next, length: source.length-next)).location != NSNotFound { return nil }
        return first.location
    }
    static func characters(_ text: String, limit: Int = 256) -> [CFRange] {
        var offset = 0
        var result: [CFRange] = []
        for scalar in text.unicodeScalars {
            let length = scalar.value > 0xFFFF ? 2 : 1
            guard offset + length <= limit else { break }
            result.append(CFRange(location: offset, length: length)); offset += length
        }
        return result
    }
}

package final class RangeInvestigator {
    let deadline: Date
    var calls = 0
    var elapsed: Double = 0
    var limitReached = false
    let maxCalls = 2048
    let cancellation: AXCancellation
    init(deadline: Date, cancellation: AXCancellation = AXCancellation()) { self.deadline = deadline; self.cancellation = cancellation }

    func inspect(_ element: AXUIElement, text: String, sourceNode: Int, viewport: CGRect) -> [String: Any] {
        let started = Date()
        defer { elapsed += Date().timeIntervalSince(started) }
        var trace: [[String: Any]] = []
        func query(_ key: String, _ input: CFTypeRef? = nil) -> CFTypeRef? {
            guard !cancellation.isCancelled, Date() < deadline, calls < maxCalls else { limitReached = true; return nil }
            recordAXQuery()
            calls += 1
            var output: CFTypeRef?
            let error: AXError
            if let input { error = AXUIElementCopyParameterizedAttributeValue(element, key as CFString, input, &output) }
            else { error = AXUIElementCopyAttributeValue(element, key as CFString, &output) }
            recordAXResult(key,error)
            return error == .success ? output : nil
        }
        // Walk from the node's valid original end, not a possibly invalid
        // NextLineEnd marker generated by ellipsis. Each native line must match
        // the remaining UTF-16 suffix exactly; never guess from glyph height.
        // Reuse each line start as the preceding line's end (no character skip).
        // See notion-fixtures/AX_LINE_DIRECTION_COMPARISON.md.
        var result: [String: Any] = ["sourceNode": sourceNode, "lineMethod": "markers-local-reverse"]
        var lines: [[String: Any]] = []
        let total = (text as NSString).length
        var offset = total
        var status = "marker_range_unavailable"
        if let whole = query("AXTextMarkerRangeForUIElement", element),
           CFGetTypeID(whole) == AXTextMarkerRangeGetTypeID() {
            var end = AXTextMarkerRangeCopyEndMarker(whole as! AXTextMarkerRange)
            while offset > 0 && lines.count < 128 && !limitReached {
                guard let boundary = query("AXPreviousLineStartTextMarkerForTextMarker", end),
                      CFGetTypeID(boundary) == AXTextMarkerGetTypeID() else {
                    status = "marker_line_start_unavailable"; break
                }
                var start = boundary as! AXTextMarker
                var pair = AXTextMarkerRangeCreate(nil, start, end)
                guard var string = query("AXStringForTextMarkerRange", pair) as? String, !string.isEmpty else {
                    status = "marker_empty_or_stalled_range"; break
                }
                if TextRangeSafety.lineCrossesNodeStart(string, before: offset, in: text) {
                    start = AXTextMarkerRangeCopyStartMarker(whole as! AXTextMarkerRange)
                    pair = AXTextMarkerRangeCreate(nil, start, end)
                    let expected = (text as NSString).substring(to: offset)
                    guard let bounded = query("AXStringForTextMarkerRange", pair) as? String,
                          bounded.utf16.elementsEqual(expected.utf16) else {
                        status = "marker_string_mismatch"; break
                    }
                    string = bounded
                }
                let length = (string as NSString).length
                let r = CFRange(location: offset - length, length: length)
                guard TextRangeSafety.retreats(r, before: offset, in: text),
                      (text as NSString).substring(with: NSRange(location: r.location, length: length)) == string else {
                    status = "marker_string_mismatch"; break
                }
                guard let value = query("AXBoundsForTextMarkerRange", pair), CFGetTypeID(value) == AXValueGetTypeID() else {
                    status = "marker_bounds_unavailable"; break
                }
                var box = CGRect.zero
                guard AXValueGetValue(value as! AXValue, .cgRect, &box),
                      box.width.isFinite, box.height.isFinite, box.minX.isFinite, box.minY.isFinite,
                      box.width > 0, box.height > 0 else {
                    status = "marker_empty_bounds"; break
                }
                lines.append(["rangeStart": r.location, "rangeLength": length, "text": string,
                              "box": rect(box), "boxKind": "marker_reverse_line", "sourceNode": sourceNode,
                              "visibility": TextRangeSafety.visibility(box, in: viewport)])
                offset = r.location
                end = start
            }
        }
        if lines.count == 128 && offset > 0 { status = "line_limit_reached" }
        result["lineRanges"] = lines.sorted { ($0["rangeStart"] as! Int) < ($1["rangeStart"] as! Int) }
        result["coveredUTF16Length"] = total - offset
        result["totalUTF16Length"] = total
        result["lineRangeStatus"] = offset == 0 ? "complete_unverified" : (limitReached ? "query_limit_reached" : status)
        result["trace"] = trace
        return result
    }
}
